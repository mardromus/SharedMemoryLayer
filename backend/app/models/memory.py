"""Memory domain models: memories, versions, sharing grants, tags, feedback, conflicts."""
from __future__ import annotations

import uuid
from datetime import datetime

from sqlalchemy import (
    CheckConstraint,
    Column,
    Computed,
    DateTime,
    Float,
    ForeignKey,
    Index,
    Integer,
    String,
    Table,
    Text,
    UniqueConstraint,
    Uuid,
)
from sqlalchemy.dialects.postgresql import JSONB, TSVECTOR
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.models.base import Base, created_at_col, str_enum, updated_at_col, uuid_pk
from app.models.enums import (
    ConflictRecordStatus,
    ConflictResolution,
    ConflictStatus,
    MemoryStatus,
    MemoryType,
    Sensitivity,
    VerificationStatus,
    Visibility,
)
from app.models.identity import Agent, Team, User

memory_tags = Table(
    "memory_tags",
    Base.metadata,
    Column("memory_id", Uuid, ForeignKey("memories.id", ondelete="CASCADE"), primary_key=True),
    Column("tag_id", Uuid, ForeignKey("tags.id", ondelete="CASCADE"), primary_key=True, index=True),
)


class Tag(Base):
    __tablename__ = "tags"

    id: Mapped[uuid.UUID] = uuid_pk()
    name: Mapped[str] = mapped_column(String(50), unique=True, nullable=False)
    created_at: Mapped[datetime] = created_at_col()


class Project(Base):
    __tablename__ = "projects"

    id: Mapped[uuid.UUID] = uuid_pk()
    name: Mapped[str] = mapped_column(String(120), unique=True, nullable=False)
    description: Mapped[str] = mapped_column(Text, default="", nullable=False)
    team_id: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("teams.id", ondelete="SET NULL"), index=True)
    created_at: Mapped[datetime] = created_at_col()

    team: Mapped[Team | None] = relationship(lazy="joined")


class Memory(Base):
    __tablename__ = "memories"
    __table_args__ = (
        CheckConstraint("importance >= 0 AND importance <= 1", name="importance_range"),
        CheckConstraint("confidence >= 0 AND confidence <= 1", name="confidence_range"),
        CheckConstraint("reliability >= 0 AND reliability <= 1", name="reliability_range"),
        CheckConstraint(
            "creator_agent_id IS NOT NULL OR creator_user_id IS NOT NULL", name="has_creator"
        ),
        Index("ix_memories_team_status_visibility", "team_id", "status", "visibility"),
        Index("ix_memories_search_tsv", "search_tsv", postgresql_using="gin"),
    )

    id: Mapped[uuid.UUID] = uuid_pk()
    title: Mapped[str] = mapped_column(String(200), nullable=False)
    content: Mapped[str] = mapped_column(Text, nullable=False)
    content_hash: Mapped[str] = mapped_column(String(64), nullable=False, index=True)
    # Generated by PostgreSQL (migration 0002); keyword half of hybrid search.
    search_tsv: Mapped[str | None] = mapped_column(
        TSVECTOR,
        Computed(
            "setweight(to_tsvector('english', coalesce(title, '')), 'A') || "
            "setweight(to_tsvector('english', coalesce(content, '')), 'B')",
            persisted=True,
        ),
        deferred=True,
    )
    memory_type: Mapped[MemoryType] = mapped_column(str_enum(MemoryType, "memory_type"), nullable=False, index=True)

    creator_agent_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("agents.id", ondelete="SET NULL"), index=True
    )
    creator_user_id: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("users.id", ondelete="SET NULL"))
    team_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("teams.id"), nullable=False, index=True)
    project_id: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("projects.id", ondelete="SET NULL"), index=True)

    visibility: Mapped[Visibility] = mapped_column(
        str_enum(Visibility, "memory_visibility"), default=Visibility.TEAM, nullable=False, index=True
    )
    sensitivity: Mapped[Sensitivity] = mapped_column(
        str_enum(Sensitivity, "memory_sensitivity"), default=Sensitivity.INTERNAL, nullable=False
    )
    status: Mapped[MemoryStatus] = mapped_column(
        str_enum(MemoryStatus, "memory_status"), default=MemoryStatus.ACTIVE, nullable=False, index=True
    )
    verification_status: Mapped[VerificationStatus] = mapped_column(
        str_enum(VerificationStatus, "verification_status"),
        default=VerificationStatus.UNVERIFIED,
        nullable=False,
        index=True,
    )
    verified_by_user_id: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("users.id", ondelete="SET NULL"))
    verified_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    conflict_status: Mapped[ConflictStatus] = mapped_column(
        str_enum(ConflictStatus, "conflict_status"), default=ConflictStatus.NONE, nullable=False
    )

    importance: Mapped[float] = mapped_column(Float, default=0.5, nullable=False)
    confidence: Mapped[float] = mapped_column(Float, default=0.8, nullable=False)
    reliability: Mapped[float] = mapped_column(Float, default=0.5, nullable=False)

    source: Mapped[str] = mapped_column(String(100), default="agent", nullable=False)
    source_ref: Mapped[str | None] = mapped_column(String(255))
    extra: Mapped[dict] = mapped_column("metadata", JSONB, default=dict, nullable=False)

    expires_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), index=True)
    embedding_id: Mapped[str | None] = mapped_column(String(64))
    embedding_model: Mapped[str | None] = mapped_column(String(128))
    parent_memory_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("memories.id", ondelete="SET NULL"), index=True
    )
    current_version: Mapped[int] = mapped_column(Integer, default=1, nullable=False)

    access_count: Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    reuse_count: Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    last_accessed_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))

    created_at: Mapped[datetime] = created_at_col(index=True)
    updated_at: Mapped[datetime] = updated_at_col()
    archived_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))

    team: Mapped[Team] = relationship(lazy="joined")
    creator_agent: Mapped[Agent | None] = relationship(lazy="joined", foreign_keys=[creator_agent_id])
    creator_user: Mapped[User | None] = relationship(lazy="joined", foreign_keys=[creator_user_id])
    project: Mapped[Project | None] = relationship(lazy="joined")
    tags: Mapped[list[Tag]] = relationship(secondary=memory_tags, lazy="selectin", order_by="Tag.name")
    access_grants: Mapped[list["MemoryAccess"]] = relationship(
        back_populates="memory", lazy="selectin", cascade="all, delete-orphan"
    )

    @property
    def tag_names(self) -> list[str]:
        return [t.name for t in self.tags]

    @property
    def allowed_team_ids(self) -> list[uuid.UUID]:
        return [g.team_id for g in self.access_grants if g.team_id is not None]

    @property
    def allowed_agent_ids(self) -> list[uuid.UUID]:
        return [g.agent_id for g in self.access_grants if g.agent_id is not None]


class MemoryVersion(Base):
    __tablename__ = "memory_versions"
    __table_args__ = (UniqueConstraint("memory_id", "version_number", name="uq_memory_versions_memory_version"),)

    id: Mapped[uuid.UUID] = uuid_pk()
    memory_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("memories.id", ondelete="CASCADE"), nullable=False, index=True)
    version_number: Mapped[int] = mapped_column(Integer, nullable=False)
    previous_version_id: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("memory_versions.id", ondelete="SET NULL"))
    title: Mapped[str] = mapped_column(String(200), nullable=False)
    content: Mapped[str] = mapped_column(Text, nullable=False)
    memory_type: Mapped[str] = mapped_column(String(32), nullable=False)
    visibility: Mapped[str] = mapped_column(String(32), nullable=False)
    tags: Mapped[list] = mapped_column(JSONB, default=list, nullable=False)
    importance: Mapped[float] = mapped_column(Float, nullable=False)
    confidence: Mapped[float] = mapped_column(Float, nullable=False)
    snapshot: Mapped[dict] = mapped_column(JSONB, default=dict, nullable=False)
    change_description: Mapped[str] = mapped_column(String(500), default="", nullable=False)
    author_agent_id: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("agents.id", ondelete="SET NULL"))
    author_user_id: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("users.id", ondelete="SET NULL"))
    created_at: Mapped[datetime] = created_at_col()

    author_agent: Mapped[Agent | None] = relationship(lazy="joined")
    author_user: Mapped[User | None] = relationship(lazy="joined")


class MemoryAccess(Base):
    """Explicit sharing grant of one memory to a team or to a single agent."""

    __tablename__ = "memory_access"
    __table_args__ = (
        CheckConstraint("(team_id IS NOT NULL) <> (agent_id IS NOT NULL)", name="exactly_one_target"),
        UniqueConstraint("memory_id", "team_id", name="uq_memory_access_memory_team"),
        UniqueConstraint("memory_id", "agent_id", name="uq_memory_access_memory_agent"),
    )

    id: Mapped[uuid.UUID] = uuid_pk()
    memory_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("memories.id", ondelete="CASCADE"), nullable=False, index=True)
    team_id: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("teams.id", ondelete="CASCADE"), index=True)
    agent_id: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("agents.id", ondelete="CASCADE"), index=True)
    permission: Mapped[str] = mapped_column(String(16), default="read", nullable=False)
    granted_by_agent_id: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("agents.id", ondelete="SET NULL"))
    granted_by_user_id: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("users.id", ondelete="SET NULL"))
    created_at: Mapped[datetime] = created_at_col()

    memory: Mapped[Memory] = relationship(back_populates="access_grants")
    team: Mapped[Team | None] = relationship(lazy="joined", foreign_keys=[team_id])
    agent: Mapped[Agent | None] = relationship(lazy="joined", foreign_keys=[agent_id])


class MemoryFeedback(Base):
    __tablename__ = "memory_feedback"
    __table_args__ = (CheckConstraint("rating >= 1 AND rating <= 5", name="rating_range"),)

    id: Mapped[uuid.UUID] = uuid_pk()
    memory_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("memories.id", ondelete="CASCADE"), nullable=False, index=True)
    agent_id: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("agents.id", ondelete="SET NULL"))
    user_id: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("users.id", ondelete="SET NULL"))
    rating: Mapped[int] = mapped_column(Integer, nullable=False)
    helpful: Mapped[bool] = mapped_column(default=True, nullable=False)
    comment: Mapped[str] = mapped_column(String(1000), default="", nullable=False)
    created_at: Mapped[datetime] = created_at_col()


class MemoryConflict(Base):
    __tablename__ = "memory_conflicts"

    id: Mapped[uuid.UUID] = uuid_pk()
    memory_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("memories.id", ondelete="CASCADE"), nullable=False, index=True)
    conflicting_memory_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("memories.id", ondelete="CASCADE"), nullable=False, index=True
    )
    similarity: Mapped[float] = mapped_column(Float, nullable=False)
    reason: Mapped[str] = mapped_column(String(500), nullable=False)
    detection_method: Mapped[str] = mapped_column(String(50), nullable=False)
    status: Mapped[ConflictRecordStatus] = mapped_column(
        str_enum(ConflictRecordStatus, "conflict_record_status"),
        default=ConflictRecordStatus.OPEN,
        nullable=False,
        index=True,
    )
    resolution: Mapped[ConflictResolution | None] = mapped_column(str_enum(ConflictResolution, "conflict_resolution"))
    resolution_note: Mapped[str] = mapped_column(String(1000), default="", nullable=False)
    resolved_by_user_id: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("users.id", ondelete="SET NULL"))
    resolved_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    created_at: Mapped[datetime] = created_at_col()

    memory: Mapped[Memory] = relationship(foreign_keys=[memory_id], lazy="joined")
    conflicting_memory: Mapped[Memory] = relationship(foreign_keys=[conflicting_memory_id], lazy="joined")
